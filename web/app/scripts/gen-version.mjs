// Writes src/lib/version.ts before a build: the app version, the canon version it was installed
// from, and the commit. CI checks messer-ui out at .messer-ui; a workstation has ~/Repos/messer-ui.
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "..");
const repoRoot = path.resolve(appRoot, "..", "..");

function version(file) {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8")).version ?? "dev";
  } catch {
    return "dev";
  }
}

const canonCandidates = [
  process.env.MESSER_UI,
  path.join(repoRoot, ".messer-ui"),
  path.resolve(process.env.HOME ?? "", "Repos/messer-ui"),
].filter(Boolean);

let canon = "dev";
for (const candidate of canonCandidates) {
  const file = path.join(candidate, "package.json");
  if (fs.existsSync(file)) {
    canon = version(file);
    break;
  }
}

let sha = process.env.GITHUB_SHA?.slice(0, 7) ?? "dev";
if (sha === "dev") {
  try {
    sha = execSync("git rev-parse --short HEAD", { cwd: repoRoot }).toString().trim();
  } catch {
    /* not a checkout */
  }
}

const out = `// Generated by scripts/gen-version.mjs — do not edit.
export const APP_VERSION = ${JSON.stringify(version(path.join(appRoot, "package.json")))};
export const CANON_VERSION = ${JSON.stringify(canon)};
export const BUILD_SHA = ${JSON.stringify(sha)};
`;
fs.writeFileSync(path.join(appRoot, "src/lib/version.ts"), out);
console.log(`version ${version(path.join(appRoot, "package.json"))} · canon ${canon} · ${sha}`);
